export const getWeekInfo = (weekNum) => {
  const w = Math.min(Math.max(Number(weekNum) || 12, 1), 40);
  if (pregnancyWeeksData[w]) return pregnancyWeeksData[w];
  
  // Interpolate for unexplicit weeks
  let closestWeek = 12;
  const keys = Object.keys(pregnancyWeeksData).map(Number).sort((a,b)=>a-b);
  for (let k of keys) {
    if (w >= k) closestWeek = k;
  }
  const base = pregnancyWeeksData[closestWeek];
  
  let trimester = '1st';
  if (w >= 28) trimester = '3rd';
  else if (w >= 13) trimester = '2nd';
  
  return {
    ...base,
    week: w,
    trimester,
    trimesterBn: trimester === '1st' ? '১ম ত্রৈমাসিক' : trimester === '2nd' ? '২য় ত্রৈমাসিক' : '৩য় ত্রৈমাসিক',
    trimesterEn: trimester === '1st' ? '1st Trimester' : trimester === '2nd' ? '2nd Trimester' : '3rd Trimester',
  };
};
